import { existsSync } from 'node:fs'
import { resolve } from 'node:path'
import type {
  ClientBuild,
  SkewProtectionAdapter,
} from '@rndsqr/usher-plugin/adapter'
import { createAssetFallback, type AssetFallbackOptions } from './worker'

const DEFAULT_BINDING = 'CHUNK_ARCHIVE'
const DEFAULT_WORKER_FILE = 'dist-worker/index.js'

export interface CloudflarePagesOptions {
  /** Name of the R2 binding on the Pages project. Default "CHUNK_ARCHIVE". */
  r2Binding?: string
}

export interface CloudflareWorkersOptions {
  /** Name of the R2 binding in the wrangler config. Default "CHUNK_ARCHIVE". */
  r2Binding?: string
  /**
   * Where to write the Worker entry, relative to the Vite root and outside outDir.
   * `.js` and `.mjs` both work as wrangler `main`. Default "dist-worker/index.js".
   */
  workerFile?: string
}

/**
 * A self-contained Worker module: the handler's own source text plus a default
 * export. It has no imports, so it deploys whether or not the deploy step bundles.
 * Taking the text from the function keeps one copy of the handler.
 */
function renderWorker(build: ClientBuild, r2Binding: string, factory: string) {
  const options: Required<AssetFallbackOptions<string>> = {
    base: build.base,
    assetsDir: build.assetsPrefix.slice(build.base.length, -1),
    r2Binding,
  }

  return `// Generated by @rndsqr/usher-cloudflare (${factory}()). Do not edit.
${createAssetFallback.toString()}

export default { fetch: createAssetFallback(${JSON.stringify(options)}) };
`
}

/**
 * Pages advanced mode: adds `_worker.js` and `_routes.json` to the client output, so
 * requests for chunks missing from the current deploy are served from R2.
 *
 *   usher({ adapter: cloudflarePages() })
 */
export function cloudflarePages(
  options: CloudflarePagesOptions = {},
): SkewProtectionAdapter {
  const binding = options.r2Binding ?? DEFAULT_BINDING

  return {
    name: 'cloudflare-pages',
    files(build) {
      const routes = {
        version: 1,
        include: [`${build.assetsPrefix}*`],
        exclude: [],
      }

      return {
        clientFiles: [
          {
            fileName: '_worker.js',
            source: renderWorker(build, binding, 'cloudflarePages'),
          },
          {
            fileName: '_routes.json',
            source: `${JSON.stringify(routes, null, 2)}\n`,
          },
        ],
        warnings: existsSync(resolve(build.root, 'functions'))
          ? [
              'Pages ignores functions/ when _worker.js exists; move those routes into the worker.',
            ]
          : [],
      }
    },
  }
}

/**
 * Workers static assets: adds a Worker entry outside the client output. Point wrangler
 * `main` at it and set `assets.run_worker_first` to the assets prefix.
 *
 *   usher({ adapter: cloudflareWorkers() })
 */
export function cloudflareWorkers(
  options: CloudflareWorkersOptions = {},
): SkewProtectionAdapter {
  const binding = options.r2Binding ?? DEFAULT_BINDING

  return {
    name: 'cloudflare-workers',
    files: build => ({
      privateFiles: [
        {
          fileName: options.workerFile ?? DEFAULT_WORKER_FILE,
          source: renderWorker(build, binding, 'cloudflareWorkers'),
        },
      ],
    }),
  }
}
