import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, isAbsolute, relative, resolve } from 'node:path'
import type {
  SkewProtectionAdapter,
  SkewProtectionContext,
} from '@app-version/vite'

const DEFAULT_BINDING = 'BUILD_CACHE'
const DEFAULT_WORKER_FILE = 'dist-worker/index.js'

export interface CloudflarePagesConfig {
  /** R2 binding name in the Pages project. Default "BUILD_CACHE". */
  r2Binding?: string
}

export interface CloudflareWorkersConfig {
  /** R2 binding name in wrangler config. Default "BUILD_CACHE". */
  r2Binding?: string
  /**
   * Output path relative to the Vite root, outside outDir. `.js` or `.mjs` both work as
   * wrangler `main`. Default "dist-worker/index.js".
   */
  workerFile?: string
}

type Target = 'pages' | 'workers'

const handlerSource = () =>
  readFileSync(new URL('./edge-handler.mjs', import.meta.url), 'utf8')

function renderWorker(
  context: SkewProtectionContext,
  binding: string,
  target: Target,
) {
  const prefix = `${context.base}${context.assetsDir}/`
  const settings = JSON.stringify({ base: context.base, binding })

  return `// Generated by @app-version/cloudflare (cloudflare${target === 'pages' ? 'Pages' : 'Workers'}()). Do not edit.
${handlerSource()}
const PREFIX = ${JSON.stringify(prefix)};
const SETTINGS = ${settings};

export default {
  fetch(request, env) {
    if (!new URL(request.url).pathname.startsWith(PREFIX)) return env.ASSETS.fetch(request);
    return serveAsset(request, env, SETTINGS);
  },
};
`
}

/**
 * Pages advanced mode: writes `_worker.js` and `_routes.json` into outDir, so requests for
 * hashed assets missing from the current deploy are served from R2.
 *
 *   appVersion({ skewProtection: cloudflarePages() })
 */
export function cloudflarePages(
  config: CloudflarePagesConfig = {},
): SkewProtectionAdapter {
  const binding = config.r2Binding ?? DEFAULT_BINDING

  return {
    bundleAssets(context) {
      if (existsSync(resolve(context.root, 'functions'))) {
        context.logger.warn(
          '[app-version] Pages ignores functions/ when _worker.js exists; move those routes into the worker.',
        )
      }

      const routes = {
        version: 1,
        include: [`${context.base}${context.assetsDir}/*`],
        exclude: [],
      }

      return [
        {
          fileName: '_worker.js',
          source: renderWorker(context, binding, 'pages'),
        },
        {
          fileName: '_routes.json',
          source: `${JSON.stringify(routes, null, 2)}\n`,
        },
      ]
    },
  }
}

/**
 * Workers static assets: writes a Worker entry outside outDir. Point wrangler `main` at it
 * and set `assets.run_worker_first` to the assets prefix.
 *
 *   appVersion({ skewProtection: cloudflareWorkers({ workerFile: "dist-worker/index.js" }) })
 */
export function cloudflareWorkers(
  config: CloudflareWorkersConfig = {},
): SkewProtectionAdapter {
  const binding = config.r2Binding ?? DEFAULT_BINDING

  return {
    writeBundle(context) {
      const out = resolve(
        context.root,
        config.workerFile ?? DEFAULT_WORKER_FILE,
      )

      const rel = relative(context.outDir, out)

      if (!rel.startsWith('..') && !isAbsolute(rel)) {
        context.error(
          '[app-version] workerFile must be outside outDir, or it is served as a public asset.',
        )
      }

      mkdirSync(dirname(out), { recursive: true })
      writeFileSync(out, renderWorker(context, binding, 'workers'))
      context.logger.info(
        `[app-version] wrote ${out}. wrangler: "main" → this file, assets.run_worker_first → ["${context.base}${context.assetsDir}/*"]`,
      )
    },
  }
}
