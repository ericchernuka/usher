import { existsSync, readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import type { ClientBuild, SkewProtectionAdapter } from '@app-version/vite'

const DEFAULT_BINDING = 'BUILD_CACHE'
const DEFAULT_WORKER_FILE = 'dist-worker/index.js'

export interface CloudflarePagesConfig {
  /** R2 binding name in the Pages project. Default "BUILD_CACHE". */
  r2Binding?: string
}

export interface CloudflareWorkersConfig {
  /** R2 binding name in wrangler config. Default "BUILD_CACHE". */
  r2Binding?: string
  /**
   * Output path relative to the Vite root, outside outDir. `.js` or `.mjs` both work as
   * wrangler `main`. Default "dist-worker/index.js".
   */
  workerFile?: string
}

const handlerSource = () =>
  readFileSync(new URL('./edge-handler.mjs', import.meta.url), 'utf8')

function renderWorker(build: ClientBuild, binding: string, factory: string) {
  const settings = JSON.stringify({ base: build.base, binding })

  return `// Generated by @app-version/cloudflare (${factory}()). Do not edit.
${handlerSource()}
const PREFIX = ${JSON.stringify(build.assetsPrefix)};
const SETTINGS = ${settings};

export default {
  fetch(request, env) {
    if (!new URL(request.url).pathname.startsWith(PREFIX)) return env.ASSETS.fetch(request);
    return serveAsset(request, env, SETTINGS);
  },
};
`
}

/**
 * Pages advanced mode: adds `_worker.js` and `_routes.json` to the client output, so
 * requests for hashed assets missing from the current deploy are served from R2.
 *
 *   appVersion({ skewProtection: cloudflarePages() })
 */
export function cloudflarePages(
  config: CloudflarePagesConfig = {},
): SkewProtectionAdapter {
  const binding = config.r2Binding ?? DEFAULT_BINDING

  return {
    name: 'cloudflare-pages',
    files(build) {
      const routes = {
        version: 1,
        include: [`${build.assetsPrefix}*`],
        exclude: [],
      }

      return {
        clientFiles: [
          {
            fileName: '_worker.js',
            source: renderWorker(build, binding, 'cloudflarePages'),
          },
          {
            fileName: '_routes.json',
            source: `${JSON.stringify(routes, null, 2)}\n`,
          },
        ],
        warnings: existsSync(resolve(build.root, 'functions'))
          ? [
              'Pages ignores functions/ when _worker.js exists; move those routes into the worker.',
            ]
          : [],
      }
    },
  }
}

/**
 * Workers static assets: adds a Worker entry outside the client output. Point wrangler
 * `main` at it and set `assets.run_worker_first` to the assets prefix.
 *
 *   appVersion({ skewProtection: cloudflareWorkers({ workerFile: "dist-worker/index.js" }) })
 */
export function cloudflareWorkers(
  config: CloudflareWorkersConfig = {},
): SkewProtectionAdapter {
  const binding = config.r2Binding ?? DEFAULT_BINDING

  return {
    name: 'cloudflare-workers',
    files: build => ({
      privateFiles: [
        {
          fileName: config.workerFile ?? DEFAULT_WORKER_FILE,
          source: renderWorker(build, binding, 'cloudflareWorkers'),
        },
      ],
    }),
  }
}
